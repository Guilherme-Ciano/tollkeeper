package main

import (
	"bytes"
	"go/token"
	"os"
	"path/filepath"
	"testing"
)

func TestCheck(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name string
		src  string
		want int
	}{
		{"clean", "package p\n\nfunc F() {}\n", 0},
		{"line comment", "package p\n\n// F does things\nfunc F() {}\n", 1},
		{"block comment", "package p\n\n/* nope */\nfunc F() {}\n", 1},
		{"trailing", "package p\n\nvar x = 1 // x\n", 1},
		{"go directive", "//go:build linux\n\npackage p\n", 0},
		{"embed directive", "package p\n\nimport _ \"embed\"\n\n//go:embed a.txt\nvar s string\n", 0},
		{"generated header", "// Code generated by x. DO NOT EDIT.\n\npackage p\n", 0},
		{"nolint is a comment", "package p\n\nvar y = 2 //nolint:all\n", 1},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := check(token.NewFileSet(), "x.go", tc.src)
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != tc.want {
				t.Fatalf("got %d violations %v, want %d", len(got), got, tc.want)
			}
		})
	}
}

func TestRun(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write := func(rel, body string) {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write("a.go", "package a\n")
	write("testdata/b.go", "package b\n\n// ignored\n")
	var out, errOut bytes.Buffer
	if code := run(dir, &out, &errOut); code != 0 {
		t.Fatalf("clean tree exit %d: %s", code, errOut.String())
	}
	write("c.go", "package a\n\n// bad\n")
	out.Reset()
	errOut.Reset()
	if code := run(dir, &out, &errOut); code != 1 {
		t.Fatalf("dirty tree exit %d", code)
	}
	write("d.go", "package a\nfunc {")
	if code := run(dir, &out, &errOut); code != 2 {
		t.Fatalf("broken tree exit %d", code)
	}
}
